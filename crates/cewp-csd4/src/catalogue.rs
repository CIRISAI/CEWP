/// A transient or active state window `[start, end)`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct WindowDecl {
    pub atom: &'static str,
    pub start: usize,
    pub end: usize,
}

impl WindowDecl {
    pub const fn new(atom: &'static str, start: usize, end: usize) -> Self {
        Self { atom, start, end }
    }

    pub fn contains_step(&self, step: usize) -> bool {
        step >= self.start && step < self.end
    }
}

/// One build step in the topology build order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StepDecl {
    pub id: &'static str,
    pub layer: &'static str,
    pub kind: &'static str,
    pub adds: &'static [&'static str],
    pub removes: &'static [&'static str],
}

/// One trace checkpoint: step ID and cumulative atoms.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TraceStepDecl {
    pub step_id: &'static str,
    pub atoms: &'static [&'static str],
}

