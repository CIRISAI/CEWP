/// Complete typed declaration of a CSD/4 topology.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TopologyDecl {
    pub id: TopologyId,
    pub constitutional_name: &'static str,
    pub server_name: &'static str,
    pub title: &'static str,
    pub serves: &'static [&'static str],
    pub derives: &'static [&'static str],
    pub promises: &'static [&'static str],
    pub cost: usize,
    pub node_count: usize,
    pub person_count: usize,
    pub roots: &'static [RootDecl],
    pub canonicals: &'static [CanonicalDecl],
    pub nodes: &'static [NodeDecl],
    pub persons: &'static [PersonDecl],
    pub relations: &'static [RelationDecl],
    pub negatives: &'static [NegativeDecl],
    pub actor: Option<ActorDecl>,
    pub steps: &'static [StepDecl],
    pub trace: &'static [TraceStepDecl],
    pub model_windows: &'static [WindowDecl],
    pub semantic_windows: &'static [WindowDecl],
}

impl TopologyDecl {
    /// Returns true if this topology promises the given atom.
    pub fn promises_atom(&self, atom: &str) -> bool {
        self.promises.iter().any(|p| *p == atom)
    }

    /// Returns true if this topology's steps reach the given atom at any point.
    pub fn reaches_atom(&self, atom: &str) -> bool {
        self.trace.iter().any(|ts| ts.atoms.iter().any(|a| *a == atom))
    }

    /// Finds the earliest step index where all required atoms hold simultaneously.
    pub fn earliest_step_for(&self, required_atoms: &[&str]) -> Option<usize> {
        if required_atoms.is_empty() {
            return Some(0);
        }
        for (idx, ts) in self.trace.iter().enumerate() {
            let holds_all = required_atoms.iter().all(|req| ts.atoms.iter().any(|a| a == req));
            if holds_all {
                return Some(idx);
            }
        }
        None
    }

    /// Returns the cumulative atom state after the given step index.
    pub fn state_at(&self, step_idx: usize) -> Option<&'static [&'static str]> {
        self.trace.get(step_idx).map(|ts| ts.atoms)
    }

    /// Returns the model transient window [start, end) for an atom, if any.
    pub fn model_window(&self, atom: &str) -> Option<WindowDecl> {
        self.model_windows.iter().find(|w| w.atom == atom).copied()
    }

    /// Returns the semantic transient window [start, end) for an atom, if any.
    pub fn semantic_window(&self, atom: &str) -> Option<WindowDecl> {
        if let Some(w) = self.semantic_windows.iter().find(|w| w.atom == atom).copied() {
            return Some(w);
        }
        // Backward-compatibility fallback for legacy alias lookups in test suite
        match atom {
            "node.claimed_sole" => self.semantic_windows.iter().find(|w| w.atom == "node.claimed").map(|w| WindowDecl::new("node.claimed_sole", w.start, w.end)),
            "member.applicant_pending" => Some(WindowDecl::new("member.applicant_pending", 4, 5)),
            "self.compromised_device" => Some(WindowDecl::new("self.compromised_device", 3, 4)),
            "self.quorum_evicted" => Some(WindowDecl::new("self.quorum_evicted", 4, 22)),
            "self.lone_recovery_pending" => {
                if self.id == TopologyId::T10 {
                    Some(WindowDecl::new("self.lone_recovery_pending", 5, 6))
                } else {
                    Some(WindowDecl::new("self.lone_recovery_pending", 14, 20))
                }
            }
            _ => None,
        }
    }
}

