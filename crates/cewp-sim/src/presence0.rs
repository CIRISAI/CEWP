/// Day type of a weekday (0 = Monday).
#[must_use]
pub const fn day_type(weekday: usize) -> usize {
    match weekday % 7 {
        0..=3 => 0,
        4 => 1,
        5 => 2,
        _ => 3,
    }
}

/// The row for an hour-of-week bin (bin 0 = Monday 00:00 local).
#[must_use]
pub fn row(how: usize) -> &'static [f64; 6] {
    let how = how % 168;
    &TABLE[day_type(how / 24)][how % 24]
}

/// Share awake (not asleep at home or elsewhere).
#[must_use]
pub fn awake(how: usize) -> f64 {
    let r = row(how);
    1.0 - r[0] - r[4]
}

/// Share at home (asleep or awake).
#[must_use]
pub fn at_home(how: usize) -> f64 {
    let r = row(how);
    r[0] + r[1]
}

/// Share whose phone is on Wi-Fi: at home always, at a workplace or school `work_wifi` of the
/// time, elsewhere `away_wifi`, travelling never. The two shares are FRONTIER inputs (the table
/// says nothing about networks).
#[must_use]
pub fn on_wifi(how: usize, work_wifi: f64, away_wifi: f64) -> f64 {
    let r = row(how);
    r[0] + r[1] + r[2] * work_wifi + (r[3] + r[4]) * away_wifi
}

/// Mean over the 168 bins of the week of `f`.
pub fn week_mean(f: impl Fn(usize) -> f64) -> f64 {
    (0..168).map(f).sum::<f64>() / 168.0
}

